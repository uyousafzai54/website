// Renders posts/*.md into src/posts.generated.js so the Worker bundle has the
// blog as plain data. Wired into wrangler's `build.command`, so it runs before
// every `wrangler dev` / `wrangler deploy`; see posts/README.md for the format.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { marked } from "marked";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const postsDir = path.join(root, "posts");
const outFile = path.join(root, "src", "posts.generated.js");

function parseFrontMatter(src, file) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(src);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim()) continue;
    const kv = /^([A-Za-z_]+):\s*(.*)$/.exec(line);
    if (!kv) throw new Error(`${file}: bad front matter line "${line}"`);
    meta[kv[1]] = kv[2].trim();
  }
  return { meta, body: m[2] };
}

function toPost(meta, body, file) {
  for (const k of ["number", "title", "date"]) {
    if (!meta[k]) throw new Error(`${file}: front matter needs "${k}"`);
  }
  const number = Number(meta.number);
  if (!Number.isInteger(number) || number < 1) throw new Error(`${file}: number must be a positive integer`);
  for (const k of ["date", "updated"]) {
    if (meta[k] && !/^\d{4}-\d{2}-\d{2}$/.test(meta[k])) throw new Error(`${file}: ${k} must be YYYY-MM-DD`);
  }
  if (meta.title !== meta.title.toLowerCase()) throw new Error(`${file}: titles are lowercase`);
  const post = { number, title: meta.title, date: meta.date };
  if (meta.updated) post.updated = meta.updated;
  if (meta.category) post.category = meta.category;
  if (meta.draft === "true") post.draft = true;
  if (meta.aliases) post.aliases = meta.aliases.split(",").map((s) => s.trim()).filter(Boolean);
  post.html = marked
    .parse(body, { gfm: true, async: false })
    .replace(/\n<\/code><\/pre>/g, "</code></pre>")
    // "[1] ..." paragraphs are reference entries (RFC-style References section).
    .replace(/<p>(\[\d+\] )/g, '<p class="ref">$1')
    .trim();
  return post;
}

const files = (await readdir(postsDir)).filter((f) => f.endsWith(".md") && f !== "README.md").sort();
const posts = [];
for (const f of files) {
  const { meta, body } = parseFrontMatter(await readFile(path.join(postsDir, f), "utf8"), f);
  posts.push(toPost(meta, body, f));
}
const seen = new Set();
for (const p of posts) {
  if (seen.has(p.number)) throw new Error(`duplicate RFC number ${p.number}`);
  seen.add(p.number);
}
posts.sort((a, b) => b.number - a.number);

await writeFile(
  outFile,
  `// Generated by scripts/build-posts.mjs from posts/*.md — do not edit.\nexport const POSTS = ${JSON.stringify(posts, null, 2)};\n`
);
console.log(`build-posts: ${posts.length} post(s) -> ${path.relative(root, outFile)}`);
