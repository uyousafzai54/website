// Renders posts/*.md into src/posts.generated.js so the Worker bundle has the
// blog as plain data. Wired into wrangler's `build.command`, so it runs before
// every `wrangler dev` / `wrangler deploy`; see posts/README.md for the format.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

let marked;
try {
  ({ marked } = await import("marked"));
} catch {
  console.error("build-posts: the 'marked' package is not installed — run `npm install` in ingress/ and retry");
  process.exit(1);
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const postsDir = path.join(root, "posts");
const outFile = path.join(root, "src", "posts.generated.js");

function parseFrontMatter(src, file) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(src);
  if (!m) throw new Error(`${file}: missing front matter`);
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim()) continue;
    const kv = /^([A-Za-z_]+):\s*(.*)$/.exec(line);
    if (!kv) throw new Error(`${file}: bad front matter line "${line}"`);
    meta[kv[1]] = kv[2].trim();
  }
  return { meta, body: m[2] };
}

function isCalendarDate(s) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) return false;
  return new Date(`${s}T00:00:00Z`).toISOString().slice(0, 10) === s;
}

function toPost(meta, body, file) {
  for (const k of ["number", "title", "date"]) {
    if (!meta[k]) throw new Error(`${file}: front matter needs "${k}"`);
  }
  const number = Number(meta.number);
  if (!Number.isInteger(number) || number < 1) throw new Error(`${file}: number must be a positive integer`);
  for (const k of ["date", "updated"]) {
    if (meta[k] && !isCalendarDate(meta[k])) throw new Error(`${file}: ${k} must be a real YYYY-MM-DD date`);
  }
  if (meta.draft !== undefined && meta.draft !== "true" && meta.draft !== "false") {
    throw new Error(`${file}: draft must be true or false`);
  }
  if (meta.title !== meta.title.toLowerCase()) throw new Error(`${file}: titles are lowercase`);
  const post = { number, title: meta.title, date: meta.date };
  if (meta.updated) post.updated = meta.updated;
  if (meta.category) post.category = meta.category;
  if (meta.draft === "true") post.draft = true;
  if (meta.aliases) post.aliases = meta.aliases.split(",").map((s) => s.trim()).filter(Boolean);
  post.html = marked
    .parse(body, { gfm: true, async: false })
    .replace(/\n<\/code><\/pre>/g, "</code></pre>")
    // "[1] ..." paragraphs are reference entries (RFC-style References section).
    .replace(/<p>(\[\d+\] )/g, '<p class="ref">$1')
    .trim();
  post.sections = [];
  post.html = post.html.replace(/<h2>(.*?)<\/h2>/g, (m, inner) => {
    const text = decodeEntities(inner.replace(/<[^>]+>/g, ""));
    const id = uniqueId(headingId(text), post.sections);
    post.sections.push({ id, text });
    return `<h2 id="${id}">${inner}</h2>`;
  });
  return post;
}

const NAMED_ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: "\u00a0", copy: "\u00a9", reg: "\u00ae", trade: "\u2122", mdash: "\u2014", ndash: "\u2013", hellip: "\u2026" };

function decodeEntities(s) {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, ref) => {
    if (ref[0] === "#") {
      const cp = ref[1].toLowerCase() === "x" ? parseInt(ref.slice(2), 16) : parseInt(ref.slice(1), 10);
      return Number.isFinite(cp) && cp >= 0 && cp <= 0x10ffff ? String.fromCodePoint(cp) : m;
    }
    return NAMED_ENTITIES[ref.toLowerCase()] ?? m;
  });
}

// "3. Internship @ Instructional Products" -> "internship-instructional-products"
function headingId(text) {
  return (
    text
      .replace(/^\d+(\.\d+)*\.?\s+/, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "section"
  );
}

function uniqueId(base, sections) {
  let id = base;
  for (let n = 2; sections.some((s) => s.id === id); n++) id = `${base}-${n}`;
  return id;
}

const files = (await readdir(postsDir)).filter((f) => f.endsWith(".md") && f !== "README.md").sort();
const posts = [];
for (const f of files) {
  const { meta, body } = parseFrontMatter(await readFile(path.join(postsDir, f), "utf8"), f);
  posts.push(toPost(meta, body, f));
}
const numbers = new Set();
const slugs = new Map();
for (const p of posts) {
  if (numbers.has(p.number)) throw new Error(`duplicate RFC number ${p.number}`);
  numbers.add(p.number);
  for (const slug of [`rfc${p.number}`, ...(p.aliases || [])]) {
    if (slugs.has(slug)) throw new Error(`slug "${slug}" is used by both RFC ${slugs.get(slug)} and RFC ${p.number}`);
    slugs.set(slug, p.number);
  }
}
posts.sort((a, b) => b.number - a.number);

await writeFile(
  outFile,
  `// Generated by scripts/build-posts.mjs from posts/*.md — do not edit.\nexport const POSTS = ${JSON.stringify(posts, null, 2)};\n`
);
console.log(`build-posts: ${posts.length} post(s) -> ${path.relative(root, outFile)}`);
